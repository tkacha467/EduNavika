from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from backend.app.domain.enums import MasteryLevel, PerformanceTrend, RetentionRiskLevel


class ExplanationRequest(BaseModel):
    """
    Request model for generating a personalized, grounded explanation.
    """
    student_id: str = Field(..., description="Student requesting the explanation")
    topic_id: str = Field(..., description="Target curriculum topic ID or name")
    query: Optional[str] = Field("Explain this topic", description="Student question or query")
    top_k: int = Field(3, ge=1, le=10, description="Number of curriculum chunks to ground upon")
    language: Optional[str] = Field("en", description="Target explanation language: en, hi, gu")


class ExplanationSource(BaseModel):
    """
    Textbook provenance for curriculum grounding.
    """
    source_document: Optional[str] = None
    source_page: Optional[int] = None
    source_reference: Optional[str] = None
    content_type: Optional[str] = None
    relevance_score: float = 0.0


class QuickCheckItem(BaseModel):
    """
    Quick self-check question grounded in the explanation.
    """
    question: str
    expected_concept: str


class StructuredExplanation(BaseModel):
    """
    Pedagogically structured explanation components.
    """
    title: str
    why_this_matters: str
    core_concept: str
    step_by_step: List[str] = Field(default_factory=list)
    common_mistake: str
    quick_check: QuickCheckItem


class PersonalizationContext(BaseModel):
    """
    Empirical student knowledge signals that influenced the explanation.
    """
    mastery_level: MasteryLevel
    accuracy: float
    recent_accuracy: Optional[float] = None
    trend: PerformanceTrend
    retention_risk: RetentionRiskLevel


class ExplanationResponse(BaseModel):
    """
    Comprehensive, personalized explanation grounded in official curriculum textbook chunks.
    Can be generated by local On-Device SLM (Qwen2.5-0.5B-Instruct) or offline deterministic rule engine.
    """
    student_id: str
    topic_id: str
    topic_title: str
    explanation: str
    structured_explanation: StructuredExplanation
    teaching_level: str
    personalization: PersonalizationContext
    sources: List[ExplanationSource]
    next_action: str
    generation_mode: str = Field(
        default="DETERMINISTIC_FALLBACK",
        description="Mode of explanation generation: 'LOCAL_LLM' or 'DETERMINISTIC_FALLBACK'"
    )
    model_name: Optional[str] = Field(
        default=None,
        description="Name of the on-device model if generated locally (e.g. Qwen2.5-0.5B-Instruct)"
    )
    inference_time_ms: Optional[int] = Field(
        default=None,
        description="Measured local inference latency in milliseconds"
    )
