logger = logging.getLogger("progress_service")


class StudentProgressService:
    """
    Consolidates empirical student progress, topic mastery, strengths/weaknesses,
    and chronological learning history for student progress tracking.
    Derives all data from verified LearningEvent and TopicPerformance records without duplication.
    Scopes curriculum dynamically to the student's authentic Standard and Subject.
    """

    @classmethod
    def _is_synthetic_subject(cls, subj: Optional[Subject]) -> bool:
        """Identifies synthetic / test subjects generated by test runs."""
        if not subj:
            return False
        name = (subj.name or "").lower()
        code = (subj.code or "").lower()
        # Flags test artifacts like 'Science Test 950691', 'Science Rec 954627', 'SR_954627', 'SE_509923'
        if re.search(r'\b(test|rec|exp)\s+\d+', name) or re.search(r'^(sci|sr|se)_\d+', code):
            return True
        return False

    @classmethod
    def _resolve_subject_scope(
        cls,
        db: Session,
        student: StudentProfile,
        subject_id: Optional[str] = None
    ) -> Optional[Subject]:
        """
        Dynamically resolves the authentic curriculum subject scope for the student:
        1. Explicit subject_id / code / name if provided.
        2. Student's empirical active subject from TopicPerformance / LearningEvent.
        3. Primary Standard 10 curriculum subject (e.g. Science & Technology for GSEB).
        4. First active non-synthetic subject under the student's Standard.
        """
        if subject_id and subject_id.strip().lower() != "all":
            clean_sid = subject_id.strip()
            # Match by Subject.id
            subj = db.query(Subject).filter(Subject.id == clean_sid).first()
            if not subj:
                # Match by Subject.code
                subj = db.query(Subject).filter(func.lower(Subject.code) == func.lower(clean_sid)).first()
            if not subj:
                # Match by exact Subject.name
                subj = db.query(Subject).filter(func.lower(Subject.name) == func.lower(clean_sid)).first()
            if not subj:
                # Match by partial Subject.name
                subj = db.query(Subject).filter(Subject.name.ilike(f"%{clean_sid}%")).first()
            if subj:
                return subj

        if subject_id and subject_id.strip().lower() == "all":
            return None

        # 1. Infer from student activity in TopicPerformance
        perf_subj = (
            db.query(Subject)
            .join(Chapter, Chapter.subject_id == Subject.id)
            .join(Topic, Topic.chapter_id == Chapter.id)
            .join(TopicPerformance, TopicPerformance.topic_id == Topic.id)
            .filter(TopicPerformance.student_id == student.id)
            .order_by(TopicPerformance.total_attempts.desc(), TopicPerformance.last_activity_at.desc())
            .first()
        )
        if perf_subj and not cls._is_synthetic_subject(perf_subj):
            return perf_subj

        # 2. Infer from LearningEvent if TopicPerformance has not yet recorded
        event_subj = (
            db.query(Subject)
            .join(Chapter, Chapter.subject_id == Subject.id)
            .join(Topic, Topic.chapter_id == Chapter.id)
            .join(LearningEvent, LearningEvent.topic_id == Topic.id)
            .filter(LearningEvent.student_id == student.id)
            .order_by(desc(LearningEvent.timestamp))
            .first()
        )
        if event_subj and not cls._is_synthetic_subject(event_subj):
            return event_subj

        # 3. Fallback for unassessed student: check standard's primary curriculum subject
        if student.standard_id:
            # Check for canonical GSEB Science & Technology
            sci = db.query(Subject).filter(
                Subject.standard_id == student.standard_id,
                Subject.code == "science_and_technology",
                Subject.is_active == True
            ).first()
            if sci:
                return sci

            # Check for any active subject named 'science' that is not synthetic
            sci_named = db.query(Subject).filter(
                Subject.standard_id == student.standard_id,
                Subject.is_active == True,
                Subject.name.ilike("%science%")
            ).all()
            for cand in sci_named:
                if not cls._is_synthetic_subject(cand):
                    return cand

            # Fallback to the first active non-synthetic subject under student's standard
            candidate_subjects = (
                db.query(Subject)
                .filter(Subject.standard_id == student.standard_id, Subject.is_active == True)
                .order_by(Subject.name.asc())
                .all()
            )
            for cand in candidate_subjects:
                if not cls._is_synthetic_subject(cand):
                    return cand

            if candidate_subjects:
                return candidate_subjects[0]

        return None

    @classmethod
    def get_student_progress(
        cls,
        db: Session,
        student_id: str,
        subject_id: Optional[str] = None,
        language: Optional[str] = "en",
    ) -> StudentProgressResponse:
        from backend.app.api.v1.endpoints.attempts import _get_or_create_student_profile

        student = _get_or_create_student_profile(db, student_id)
        if not student:
            raise ValueError(f"Student profile '{student_id}' not found.")

        target_lang = language or (student.preferred_language if student else "en") or "en"

        # 1. Resolve authentic curriculum subject scope
        target_subject = cls._resolve_subject_scope(db, student, subject_id)

        topic_query = (
            db.query(Topic)
            .join(Chapter, Topic.chapter_id == Chapter.id)
            .join(Subject, Chapter.subject_id == Subject.id)
            .filter(Topic.is_active == True)
        )
        if student.standard_id:
            topic_query = topic_query.filter(Subject.standard_id == student.standard_id)

        if target_subject:
            topic_query = topic_query.filter(Subject.id == target_subject.id)

        all_topics = topic_query.order_by(Topic.topic_order.asc(), Topic.title.asc()).all()

        # Filter strictly pedagogical curriculum topics (excluding placeholders and synthetic test topics)
        eligible_topics = [
            t for t in all_topics
            if RecommendationEngineService.is_eligible_curriculum_topic(db, student, t)
            and not cls._is_synthetic_subject(t.chapter.subject if t.chapter else None)
        ]
        if not eligible_topics and all_topics:
            eligible_topics = [
                t for t in all_topics
                if RecommendationEngineService.is_eligible_curriculum_topic(db, student, t)
            ]

        # 2. Compute TopicProgressItems
        topic_items: List[TopicProgressItem] = []
        mastery_dist = MasteryDistribution()

        for topic in eligible_topics:
            profile = KnowledgeModelService.calculate_topic_profile(db, student.id, topic)

            diff, reason = AdaptivePracticeService.determine_difficulty(
                profile=profile,
                retention_risk=profile.retention_risk,
                trend=profile.trend,
            )

            action_map = {
                "FOUNDATIONAL": "FOUNDATIONAL_PRACTICE",
                "GUIDED": "GUIDED_PRACTICE",
                "APPLICATION": "APPLICATION_PRACTICE",
                "CHALLENGE": "CHALLENGE_PRACTICE",
            }
            rec_action = action_map.get(diff, "FOUNDATIONAL_PRACTICE")

            # Update distribution
            if profile.mastery_level == MasteryLevel.UNASSESSED or profile.total_attempts == 0:
                mastery_dist.unassessed += 1
            elif profile.mastery_level == MasteryLevel.NOVICE:
                mastery_dist.novice += 1
            elif profile.mastery_level == MasteryLevel.DEVELOPING:
                mastery_dist.developing += 1
            elif profile.mastery_level == MasteryLevel.PROFICIENT:
                mastery_dist.proficient += 1
            elif profile.mastery_level == MasteryLevel.MASTERED:
                mastery_dist.mastered += 1

            topic_items.append(
                TopicProgressItem(
                    topic_id=topic.id,
                    topic_title=topic.title,
                    subject_name=localize_subject_name(profile.subject_name, target_lang),
                    total_attempts=profile.total_attempts,
                    correct_attempts=profile.correct_attempts,
                    accuracy=profile.accuracy,
                    mastery_level=profile.mastery_level,
                    recent_accuracy=profile.recent_accuracy,
                    trend=profile.trend,
                    retention_risk=profile.retention_risk,
                    recommended_action=rec_action,
                    recommended_difficulty=diff,
                )
            )

        # 3. Overall Student Progress
        total_attempts = sum(t.total_attempts for t in topic_items)
        correct_attempts = sum(t.correct_attempts for t in topic_items)
        overall_accuracy = (
            round((correct_attempts / total_attempts) * 100.0, 2)
            if total_attempts > 0 else 0.0
        )
        topics_studied = sum(1 for t in topic_items if t.total_attempts > 0)
        total_topics_available = len(topic_items)

        # Calculate overall student trend from recent evaluative events in this scope
        scoped_topic_ids = [t.topic_id for t in topic_items]
        eval_events = (
            db.query(LearningEvent)
            .filter(
                LearningEvent.student_id == student.id,
                LearningEvent.correctness.isnot(None),
                LearningEvent.topic_id.in_(scoped_topic_ids) if scoped_topic_ids else True,
            )
            .order_by(LearningEvent.timestamp.asc())
            .all()
        )

        overall_trend = "INSUFFICIENT_DATA"
        if len(eval_events) >= 4:
            half = len(eval_events) // 2
            prior_half = eval_events[:half]
            recent_half = eval_events[half:]
            prior_acc = (sum(1 for e in prior_half if e.correctness is True) / len(prior_half)) * 100.0
            recent_acc = (sum(1 for e in recent_half if e.correctness is True) / len(recent_half)) * 100.0
            diff_acc = recent_acc - prior_acc
            if diff_acc >= 15.0:
                overall_trend = "IMPROVING"
            elif diff_acc <= -15.0:
                overall_trend = "DECLINING"
            else:
                overall_trend = "STABLE"

        # Most recent activity timestamp within scope
        latest_event = (
            db.query(LearningEvent)
            .filter(
                LearningEvent.student_id == student.id,
                LearningEvent.topic_id.in_(scoped_topic_ids) if scoped_topic_ids else True,
            )
            .order_by(desc(LearningEvent.timestamp))
            .first()
        )
        recent_activity_at = latest_event.timestamp if latest_event else None

        overall_summary = OverallProgressSummary(
            total_attempts=total_attempts,
            correct_attempts=correct_attempts,
            overall_accuracy=overall_accuracy,
            topics_studied=topics_studied,
            total_topics_available=total_topics_available,
            mastery_distribution=mastery_dist,
            overall_trend=overall_trend,
            recent_activity_at=recent_activity_at,
            subject_id=target_subject.id if target_subject else "all",
            subject_name=localize_subject_name(target_subject.name if target_subject else "All Subjects", target_lang),
        )

        # 4. Strengths and Weaknesses Identification
        strengths: List[TopicProgressItem] = []
        weaknesses: List[TopicProgressItem] = []
        developing: List[TopicProgressItem] = []

        for item in topic_items:
            if item.total_attempts == 0:
                continue

            if (
                item.accuracy < 50.0
                or item.retention_risk == RetentionRiskLevel.HIGH
                or item.mastery_level == MasteryLevel.NOVICE
            ):
                weaknesses.append(item)
            elif (
                (item.accuracy >= 70.0 or item.mastery_level in (MasteryLevel.PROFICIENT, MasteryLevel.MASTERED))
                and item.retention_risk != RetentionRiskLevel.HIGH
            ):
                strengths.append(item)
            else:
                developing.append(item)

        sw_summary = StrengthsWeaknessesSummary(
            strengths=strengths,
            weaknesses=weaknesses,
            developing=developing,
            unassessed_count=mastery_dist.unassessed,
        )

        # 5. Chronological Learning Journey (most recent first, up to 20 events)
        journey_events = (
            db.query(LearningEvent)
            .filter(
                LearningEvent.student_id == student.id,
                LearningEvent.topic_id.in_(scoped_topic_ids) if scoped_topic_ids else True,
            )
            .order_by(desc(LearningEvent.timestamp))
            .limit(20)
            .all()
        )

        learning_journey: List[LearningJourneyItem] = []
        for e in journey_events:
            t_title = e.topic.title if e.topic else "Curriculum Topic"
            s_name = (
                e.topic.chapter.subject.name
                if e.topic and e.topic.chapter and e.topic.chapter.subject
                else "Science & Technology"
            )
            ev_meta = e.event_metadata or {}
            diff_level = ev_meta.get("difficulty")
            ev_type_str = e.event_type.value if hasattr(e.event_type, "value") else str(e.event_type)

            learning_journey.append(
                LearningJourneyItem(
                    event_id=e.id,
                    timestamp=e.timestamp,
                    topic_id=e.topic_id,
                    topic_title=t_title,
                    subject_name=localize_subject_name(s_name, target_lang),
                    event_type=ev_type_str,
                    correctness=e.correctness,
                    score=e.score,
                    difficulty=diff_level,
                    response_time_ms=e.response_time_ms,
                )
            )

        return StudentProgressResponse(
            student_id=student.id,
            overall=overall_summary,
            topics=topic_items,
            strengths_weaknesses=sw_summary,
            learning_journey=learning_journey,
        )


student_progress_service = StudentProgressService()
