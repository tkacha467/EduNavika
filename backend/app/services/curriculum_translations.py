def localize_question(question: Dict[str, Any], lang: Optional[str] = "en") -> Dict[str, Any]:
    """
    Returns a copy of the canonical question localized into target language (en, hi, gu).
    Preserves question ID, topic_id, difficulty, source_document, source_page,
    and source_chunk_id identically.
    Falls back to English if translation is missing or language is unsupported.
    """
    if not lang or lang.lower() == "en":
        return question.copy()

    lang_code = lang.lower()
    translations_for_lang = QUESTION_TRANSLATIONS.get(lang_code, {})
    qid = question.get("id")
    trans = translations_for_lang.get(qid)
    if not trans:
        return question.copy()

    localized = question.copy()
    localized["question"] = trans["question"]
    localized["options"] = list(trans["options"])
    localized["correct_answer"] = trans["correct_answer"]
    localized["explanation"] = trans["explanation"]
    return localized


def localize_subject_name(subject_name: str, lang: Optional[str] = "en") -> str:
    """Translates subject name into Hindi or Gujarati."""
    if not lang or lang.lower() == "en":
        return subject_name
    lang_code = lang.lower()
    if lang_code == "hi":
        if "Science" in subject_name:
            return "विज्ञान एवं प्रौद्योगिकी"
        if "Math" in subject_name:
            return "गणित"
        if "All" in subject_name:
            return "सभी विषय"
    elif lang_code == "gu":
        if "Science" in subject_name:
            return "વિજ્ઞાન અને ટેકનોલોજી"
        if "Math" in subject_name:
            return "ગણિત"
        if "All" in subject_name:
            return "બધા વિષયો"
    return subject_name


