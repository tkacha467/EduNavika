def localize_badge(badge_id: str, lang: Optional[str] = "en") -> Tuple[str, str, str]:
    """Returns (name, description, icon) for a badge in English, Hindi, or Gujarati."""
    target_lang = (lang or "en").lower()
    if target_lang not in ("en", "hi", "gu"):
        target_lang = "en"
    badge_info = BADGE_METADATA.get(badge_id, {
        "icon": "🎖️",
        "en": {"name": badge_id, "desc": "Achievement unlocked"},
        "hi": {"name": badge_id, "desc": "उपलब्धि अनलॉक हुई"},
        "gu": {"name": badge_id, "desc": "સિદ્ધિ પ્રાપ્ત થઈ"},
    })
    icon = badge_info.get("icon", "🎖️")
    content = badge_info.get(target_lang, badge_info.get("en", {"name": badge_id, "desc": ""}))
    return content.get("name", badge_id), content.get("desc", ""), icon


