    if not lang or lang.lower() == "en":
        if priority == "URGENT" or risk == "HIGH":
            return f"Urgent revision required for '{topic_title}' due to elevated retention decay and low accuracy. Immediate practice recommended to arrest forgetting{page_ref_en}."
        if priority == "HIGH":
            return f"High priority revision for '{topic_title}' scheduled within 1-2 days to consolidate developing conceptual understanding{page_ref_en}."
        if priority == "MEDIUM":
            return f"Progressive spaced repetition for '{topic_title}' scheduled to build durable long-term retention."
        return f"Maintenance review scheduled for '{topic_title}' following high conceptual mastery."

    lang_code = lang.lower()
    if lang_code == "hi":
        if priority == "URGENT" or risk == "HIGH":
            return f"'{topic_title}' के लिए स्मृति ह्रास और कम सटीकता दर्ज की गई। भूलने की प्रक्रिया रोकने के लिए तत्काल पुनरावलोकन आवश्यक है{page_ref_hi}।"
        if priority == "HIGH":
            return f"'{topic_title}' पर वैचारिक समझ को मजबूत करने के लिए 1-2 दिनों के भीतर पुनरावलोकन अनुशंसित है{page_ref_hi}।"
